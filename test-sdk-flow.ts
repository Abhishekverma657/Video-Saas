import { OmniRTC } from "./packages/sdk/src/index.js";

async function runTest() {
  console.log("==================================================");
  console.log("  AuraRTC SDK & API Key Live Flow Test");
  console.log("==================================================\n");

  // Step 1: Login developer to retrieve their issued App ID and Secret
  console.log("1️⃣  Authenticating developer with AuraRTC SaaS API...");
  const authRes = await fetch("http://localhost:5001/api/v1/auth/login", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ email: "demo@omnirtc.io", password: "Password@123" }),
  });
  const authData = await authRes.json();
  const project = authData.data.projects[0];

  console.log(`✅ Developer authenticated: ${authData.data.user.name}`);
  console.log(`🔑 App ID:     ${project.appId}`);
  console.log(`🔒 App Secret: ${project.appSecret}`);
  console.log(`⏱️  Quota:      ${project.totalMinutesUsed} / ${project.freeQuotaMinutes} mins\n`);

  // Step 2: Initialize the OmniRTC SDK using the developer's credentials
  console.log("2️⃣  Initializing OmniRTC Client SDK with App Credentials...");
  const rtc = new OmniRTC({
    appId: project.appId,
    appSecret: project.appSecret,
    apiUrl: "http://localhost:5001/api/v1",
  });
  console.log("✅ OmniRTC SDK successfully instantiated.\n");

  // Step 3: Request a signed WebRTC Access Token for a meeting room
  console.log("3️⃣  Requesting signed room token via SDK getJoinToken()...");
  const tokenData = await rtc.getJoinToken({
    roomName: "live-boardroom-alpha",
    identity: "developer_abhishek_01",
    name: "Abhishek",
  });

  console.log("✅ Token successfully generated by AuraRTC Media Gateway!");
  console.log(`   🎬 Target SFU:   ${tokenData.serverUrl}`);
  console.log(`   🏷️  Room Name:    ${tokenData.roomName}`);
  console.log(`   👤 Identity:     ${tokenData.identity}`);
  console.log(`   🎫 Token (JWT):  ${tokenData.token.substring(0, 40)}...\n`);

  // Step 4: Test security - what happens with invalid keys
  console.log("4️⃣  Verifying security: Testing with an INVALID App Secret...");
  try {
    const invalidRtc = new OmniRTC({
      appId: project.appId,
      appSecret: "sec_fake_unauthorized_key_999",
      apiUrl: "http://localhost:5001/api/v1",
    });
    await invalidRtc.getJoinToken({
      roomName: "secure-room",
      identity: "hacker_01",
    });
    console.log("❌ ERROR: Invalid key was accepted!");
  } catch (err: any) {
    console.log(`✅ Security Verified: Gateway correctly rejected invalid key with error: "${err.message}"\n`);
  }

  console.log("==================================================");
  console.log("  🎉 All SDK & Key Verification Tests PASSED!");
  console.log("==================================================");
}

runTest().catch((err) => {
  console.error("Test failed:", err);
  process.exit(1);
});
